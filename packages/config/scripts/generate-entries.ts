// Writes the published entry files from the built rule data, so the Biome
// JSONC files and the Oxlint/Oxfmt modules share one definition with the
// tasks that render xtarterize's configs. Node runs this file directly; the
// build type-checks it first (see scripts/tsconfig.json).
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import type { BiomePreset, OxlintPreset } from '../dist/index.mjs';
import {
  biomeCoreLayer,
  biomePresets,
  oxfmtLayer,
  oxlintCoreLayer,
  oxlintPresets,
} from '../dist/index.mjs';

const distDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');

const GENERATED = 'Generated by scripts/generate-entries.ts. Do not edit.';

async function write(relativePath: string, content: string): Promise<void> {
  const target = join(distDir, relativePath);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, content);
}

function json(value: unknown): string {
  return JSON.stringify(value, null, 2);
}

/** The object's properties as source lines, without the enclosing braces. */
function objectBody(value: object): string {
  return json(value).slice(1, -1).trim();
}

function biomeEntry(preset: BiomePreset): string {
  const layer = preset === 'core' ? biomeCoreLayer() : {};
  return `// ${GENERATED}\n${json({
    extends: [`ultracite/biome/${preset}`],
    root: false,
    ...layer,
  })}\n`;
}

/**
 * Whether the Ultracite preset loads JS plugins. Oxlint loads them through
 * `extends` either way, but Knip reads `jsPlugins` only from the root config,
 * so the entry re-exports them for a consumer to repeat at its root
 * (`jsPlugins: landmines.jsPlugins`).
 */
async function hasJsPlugins(preset: OxlintPreset): Promise<boolean> {
  const { default: config } = (await import(`ultracite/oxlint/${preset}`)) as {
    default: { jsPlugins?: Array<unknown> };
  };
  return (config.jsPlugins?.length ?? 0) > 0;
}

async function oxlintEntry(preset: OxlintPreset): Promise<string> {
  const lines = ['extends: [ultracite],'];
  if (await hasJsPlugins(preset)) {
    lines.push('jsPlugins: ultracite.jsPlugins,');
  }
  if (preset === 'core') {
    lines.push(`${objectBody(oxlintCoreLayer())},`);
  }
  return `// ${GENERATED}
import ultracite from "ultracite/oxlint/${preset}";

export default {
  ${lines.join('\n  ')}
};
`;
}

const oxlintTypes = `import type { OxlintConfig } from "oxlint";

declare const config: OxlintConfig;

export default config;
`;

function oxfmtEntry(): string {
  return `// ${GENERATED}
import ultracite from "ultracite/oxfmt";

export default {
  ...ultracite,
  ${objectBody(oxfmtLayer())},
};
`;
}

const oxfmtTypes = `import type { OxfmtConfig } from "oxfmt";

declare const config: OxfmtConfig;

export default config;
`;

const writes: Array<Promise<void>> = [
  ...biomePresets.map((preset) =>
    write(`biome/${preset}.jsonc`, biomeEntry(preset))
  ),
  ...oxlintPresets.flatMap((preset) => [
    oxlintEntry(preset).then((entry) => write(`oxlint/${preset}.mjs`, entry)),
    write(`oxlint/${preset}.d.mts`, oxlintTypes),
  ]),
  write('oxfmt/index.mjs', oxfmtEntry()),
  write('oxfmt/index.d.mts', oxfmtTypes),
];

await Promise.all(writes);
